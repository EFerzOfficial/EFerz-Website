export function getLocalizedServiceText(
  serviceId: string,
  lang: Language,
  fallback: {
    title: string;
    environmentName: string;
    tagline: string;
    summary: string;
    orbitalHeadline: string;
    orbitalSub: string;
    primaryNodeTitle: string;
    primaryNodeCode: string;
    primaryNodeTelemetry: string[];
    computeCoreModel: string;
    computeCoreSpec: string;
    intelligenceLayerTitle: string;
    deploymentTitle: string;
    deploymentStatement: string;
  }
) {
  if (lang !== 'ar') return fallback;
  const ar = SERVICE_ARABIC_MAP[serviceId];
  if (!ar) return fallback;
  return {
    title: ar.titleAr,
    environmentName: ar.environmentNameAr,
    tagline: ar.taglineAr,
    summary: ar.summaryAr,
    orbitalHeadline: ar.orbitalHeadlineAr,
    orbitalSub: ar.orbitalSubAr,
    primaryNodeTitle: ar.primaryNodeTitleAr,
    primaryNodeCode: ar.primaryNodeCodeAr,
    primaryNodeTelemetry: ar.primaryNodeTelemetryAr,
    computeCoreModel: ar.computeCoreModelAr,
    computeCoreSpec: ar.computeCoreSpecAr,
    intelligenceLayerTitle: ar.intelligenceLayerTitleAr,
    deploymentTitle: ar.deploymentTitleAr,
    deploymentStatement: ar.deploymentStatementAr,
  };
}
